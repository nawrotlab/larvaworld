"""Curated catalog of beginner-facing behavioral scenarios.

The registry ships 57 experiment configurations whose IDs (``PItest_off_OSN``,
``RvsS_on_q15``, ``noMB_patch_grid``) mean nothing to a newcomer, and whose
durations range from 30 seconds to 24 hours. This module hand-picks a small set,
gives each a human title and an explanation, and caps how long it runs, so the
Explore app can offer "pick one and watch" with no configuration.

The behavioral grouping mirrors the categories used in ``Exp_dict`` in
``larvaworld.lib.reg.stored_confs.sim_conf``. That grouping is flattened away
when configs are materialized into the registry, so it is re-declared here.
This is deliberately portal-side curation: it must not leak into core config.

Data only - no Panel imports, so this stays cheap and unit-testable.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Scenario:
    """One curated, ready-to-watch experiment.

    Attributes:
        id: Stable identifier used in URLs and tests.
        exp_id: A stored ``Exp`` configuration ID; must exist in the registry.
        category: Behavioral grouping used to section the gallery.
        title: Human-readable name shown on the card.
        teaser: One sentence describing what the viewer will see.
        explanation: Two to four sentences on what the behavior means.
        step_cap: Maximum simulation steps for the Explore run.
        n_agents: Number of larvae, kept small so individuals stay legible.
        literature: Optional source publication for the paradigm.
        watch_for: Short bullet hints on what to look at while it runs.
    """

    id: str
    exp_id: str
    category: str
    title: str
    teaser: str
    explanation: str
    step_cap: int = 600
    n_agents: int = 8
    literature: str | None = None
    watch_for: tuple[str, ...] = field(default_factory=tuple)


