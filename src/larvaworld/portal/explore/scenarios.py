def scenario_by_id(scenario_id: str) -> Scenario | None:
    """Return the scenario with this ID, or ``None``."""
    for scenario in SCENARIOS:
        if scenario.id == scenario_id:
            return scenario
    return None


def scenarios_by_category() -> dict[str, list[Scenario]]:
    """Group the catalog by category, in :data:`CATEGORY_ORDER`."""
    grouped: dict[str, list[Scenario]] = {}
    for category in CATEGORY_ORDER:
        matching = [s for s in SCENARIOS if s.category == category]
        if matching:
            grouped[category] = matching
    return grouped


def validate_scenarios(*, known_exp_ids: set[str] | None = None) -> None:
    """Check catalog invariants.

    Args:
        known_exp_ids: Experiment IDs available in the registry. When omitted,
            registry membership is not checked (keeps unit tests import-light).

    Raises:
        ValueError: If any invariant is violated.
    """

    def _err(msg: str) -> None:
        raise ValueError(f"[larvaworld.portal.explore] {msg}")

    ids = [s.id for s in SCENARIOS]
    if len(ids) != len(set(ids)):
        _err("Duplicate scenario ids")

    for scenario in SCENARIOS:
        if scenario.category not in CATEGORY_TITLES:
            _err(
                f"Scenario '{scenario.id}' has unknown category "
                f"'{scenario.category}'"
            )
        if not scenario.title.strip() or not scenario.teaser.strip():
            _err(f"Scenario '{scenario.id}' is missing title or teaser")
        if not scenario.explanation.strip():
            _err(f"Scenario '{scenario.id}' is missing an explanation")
        if scenario.step_cap <= 0 or scenario.step_cap > 2000:
            _err(
                f"Scenario '{scenario.id}' step_cap={scenario.step_cap} is outside "
                "the bounded range (1..2000)"
            )
        if scenario.n_agents <= 0 or scenario.n_agents > 50:
            _err(
                f"Scenario '{scenario.id}' n_agents={scenario.n_agents} is outside "
                "the legible range (1..50)"
            )
        if known_exp_ids is not None and scenario.exp_id not in known_exp_ids:
            _err(
                f"Scenario '{scenario.id}' references unknown experiment "
                f"'{scenario.exp_id}'"
            )
